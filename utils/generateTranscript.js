const fs = require('fs');
const path = require('path');
const { AttachmentBuilder } = require('discord.js');

async function generateTranscript(channel, client) {
    
    let allMessages = [];
    let lastId = null;
    for (let i = 0; i < 5; i++) {
        const options = { limit: 100 };
        if (lastId) options.before = lastId;
        const batch = await channel.messages.fetch(options);
        if (batch.size === 0) break;
        allMessages.push(...batch.values());
        lastId = batch.last().id;
        if (batch.size < 100) break;
    }
    const sorted = allMessages.sort((a, b) => a.createdTimestamp - b.createdTimestamp);

    let content = `
    <html>
    <head>
        <title>Ticket Transcript</title>
        <style>
            body { font-family: Arial, sans-serif; background-color: #f4f4f4; padding: 20px; }
            .msg { background: white; padding: 10px; margin-bottom: 10px; border-left: 4px solid #00bfff; }
            .author { font-weight: bold; }
            .timestamp { color: #999; font-size: 12px; }
            .watermark { text-align: center; font-size: 12px; color: #888; margin-top: 20px; }
        </style>
    </head>
    <body>
        <h2>Ticket Transcript - ${channel.name}</h2>
    `;

    for (const msg of sorted) {
        
        const safeContent = (msg.content || '*Embed/Attachment*')
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#039;');
        const safeTag = (msg.author.tag || 'Unknown')
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;');
        content += `
        <div class="msg">
            <div class="author">${safeTag}</div>
            <div class="timestamp">${new Date(msg.createdTimestamp).toLocaleString()}</div>
            <div class="content">${safeContent}</div>
        </div>
        `;
    }

    content += `<div class="watermark">Transcript generated by shiva - fluenosity</div></body></html>`;

    const transcriptsDir = path.join(__dirname, '../transcripts');
    const fileName = `${channel.id}.html`;
    const filePath = path.join(transcriptsDir, fileName);

    if (!fs.existsSync(transcriptsDir)) {
        fs.mkdirSync(transcriptsDir);
    }

    fs.writeFileSync(filePath, content);

    const attachment = new AttachmentBuilder(filePath).setName(fileName);

    
    return { attachment, fileName };
}

module.exports = generateTranscript;
